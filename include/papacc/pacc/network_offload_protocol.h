#ifndef PAPACC_NETWORK_OFFLOAD_PROTOCOL_H
#define PAPACC_NETWORK_OFFLOAD_PROTOCOL_H

#include "frame.h"
#include "message_types.h"

#define PAPACC_NETWORK_DESTINATION_CAPACITY 255U
#define PAPACC_NETWORK_ALPN_COUNT_MAX 8U
#define PAPACC_NETWORK_ALPN_PROTOCOL_CAPACITY 32U
#define PAPACC_NETWORK_DATA_MAX_PAYLOAD 16384U
#define PAPACC_NETWORK_OPEN_MAX_PAYLOAD (8U+PAPACC_NETWORK_DESTINATION_CAPACITY+PAPACC_NETWORK_ALPN_COUNT_MAX*(1U+PAPACC_NETWORK_ALPN_PROTOCOL_CAPACITY))

typedef enum PAPACC_NETWORK_DESTINATION_KIND {
    PAPACC_NETWORK_DESTINATION_DNS_ASCII=1,
    PAPACC_NETWORK_DESTINATION_IPV4=2,
    PAPACC_NETWORK_DESTINATION_IPV6=3
} PAPACC_NETWORK_DESTINATION_KIND;
typedef enum PAPACC_NETWORK_TRANSPORT_MODE {
    PAPACC_NETWORK_TRANSPORT_TCP_PLAIN=1,
    PAPACC_NETWORK_TRANSPORT_TLS_REQUIRED=2
} PAPACC_NETWORK_TRANSPORT_MODE;
typedef struct PAPACC_NETWORK_ALPN {
    PAPACC_U8 size;
    PAPACC_U8 bytes[PAPACC_NETWORK_ALPN_PROTOCOL_CAPACITY];
} PAPACC_NETWORK_ALPN;
typedef struct PAPACC_NETWORK_OPEN {
    PAPACC_NETWORK_DESTINATION_KIND destination_kind;
    PAPACC_NETWORK_TRANSPORT_MODE transport_mode;
    PAPACC_U16 port;
    PAPACC_U16 destination_size;
    PAPACC_U8 destination[PAPACC_NETWORK_DESTINATION_CAPACITY];
    PAPACC_U8 alpn_count;
    PAPACC_NETWORK_ALPN alpn[PAPACC_NETWORK_ALPN_COUNT_MAX];
} PAPACC_NETWORK_OPEN;
#define PAPACC_NETWORK_OPEN_INITIALIZER { PAPACC_NETWORK_DESTINATION_DNS_ASCII, \
    PAPACC_NETWORK_TRANSPORT_TCP_PLAIN,0U,0U,{0},0U,{{0U,{0}}} }

typedef enum PAPACC_NETWORK_OPEN_STATUS {
    PAPACC_NETWORK_OPEN_OK=0,
    PAPACC_NETWORK_OPEN_DENIED=1,
    PAPACC_NETWORK_OPEN_UNSUPPORTED=2,
    PAPACC_NETWORK_OPEN_UNAVAILABLE=3,
    PAPACC_NETWORK_OPEN_FAILED=4
} PAPACC_NETWORK_OPEN_STATUS;

/* Portable non-clean terminal reason. Unknown nonzero values remain failures. */
typedef PAPACC_U16 PAPACC_NETWORK_TERMINAL_REASON;
#define PAPACC_NETWORK_TERMINAL_REASON_UNSPECIFIED ((PAPACC_NETWORK_TERMINAL_REASON)0U)
#define PAPACC_NETWORK_TERMINAL_REASON_TLS_TRUNCATED ((PAPACC_NETWORK_TERMINAL_REASON)1U)

typedef struct PAPACC_NETWORK_ABORT_REASON_MESSAGE {
    PAPACC_NETWORK_TERMINAL_REASON reason;
} PAPACC_NETWORK_ABORT_REASON_MESSAGE;
#define PAPACC_NETWORK_ABORT_REASON_MESSAGE_INITIALIZER { \
    PAPACC_NETWORK_TERMINAL_REASON_UNSPECIFIED }

PAPACC_RESULT papacc_network_open_encode(const PAPACC_NETWORK_OPEN *,
    PAPACC_U8 *,PAPACC_SIZE,PAPACC_SIZE *);
PAPACC_RESULT papacc_network_open_decode(const PAPACC_U8 *,PAPACC_SIZE,
    PAPACC_NETWORK_OPEN *);
PAPACC_RESULT papacc_network_open_result_encode(PAPACC_NETWORK_OPEN_STATUS,
    PAPACC_U8 *,PAPACC_SIZE,PAPACC_SIZE *);
PAPACC_RESULT papacc_network_open_result_decode(const PAPACC_U8 *,PAPACC_SIZE,
    PAPACC_NETWORK_OPEN_STATUS *);
PAPACC_RESULT papacc_network_data_validate(PAPACC_SIZE);
PAPACC_RESULT papacc_network_terminal_validate(PAPACC_U16,PAPACC_SIZE);
PAPACC_RESULT papacc_network_abort_reason_encode(
    const PAPACC_NETWORK_ABORT_REASON_MESSAGE *,PAPACC_U8 *,PAPACC_SIZE,
    PAPACC_SIZE *);
PAPACC_RESULT papacc_network_abort_reason_decode(const PAPACC_U8 *,PAPACC_SIZE,
    PAPACC_NETWORK_ABORT_REASON_MESSAGE *);
PAPACC_FRAME_HEADER papacc_network_frame_header(PAPACC_U16,PAPACC_U32);

#endif
