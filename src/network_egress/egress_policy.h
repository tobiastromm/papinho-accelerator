#ifndef PAPACC_EGRESS_POLICY_H
#define PAPACC_EGRESS_POLICY_H

#include "network_endpoint.h"
#include "network_interface.h"

#define PAPACC_EGRESS_PROFILE_NAME_CAPACITY 48U
#define PAPACC_DESTINATION_HOSTNAME_CAPACITY 253U
#define PAPACC_EGRESS_SENSITIVE_LOOPBACK 0x0001UL
#define PAPACC_EGRESS_SENSITIVE_LINK_LOCAL 0x0002UL
#define PAPACC_EGRESS_SENSITIVE_PRIVATE 0x0004UL
#define PAPACC_EGRESS_SENSITIVE_SHARED 0x0008UL
#define PAPACC_EGRESS_SENSITIVE_METADATA 0x0010UL
#define PAPACC_EGRESS_SENSITIVE_MANAGEMENT 0x0020UL
#define PAPACC_EGRESS_SENSITIVE_LOCAL_SERVICE 0x0040UL

typedef enum PAPACC_EGRESS_DECISION { PAPACC_EGRESS_DENY=0,
    PAPACC_EGRESS_ALLOW=1,PAPACC_EGRESS_ERROR=2 } PAPACC_EGRESS_DECISION;
typedef struct PAPACC_EGRESS_PROFILE {
    PAPACC_U32 profile_id;
    char name[PAPACC_EGRESS_PROFILE_NAME_CAPACITY];
    PAPACC_NETWORK_INTERFACE_PERSISTENT_ID interface_id;
    PAPACC_NETWORK_ENDPOINT source_endpoint;
    PAPACC_BOOL use_default_route;
    PAPACC_BOOL available;
} PAPACC_EGRESS_PROFILE;
#define PAPACC_EGRESS_PROFILE_INITIALIZER {0U,{0}, \
    PAPACC_NETWORK_INTERFACE_PERSISTENT_ID_INITIALIZER, \
    PAPACC_NETWORK_ENDPOINT_INITIALIZER,PAPACC_FALSE,PAPACC_FALSE}

typedef PAPACC_EGRESS_DECISION (*PAPACC_EGRESS_HOST_POLICY_FN)(void *,
    const char *,PAPACC_SIZE,PAPACC_U16);
typedef PAPACC_EGRESS_DECISION (*PAPACC_EGRESS_ENDPOINT_POLICY_FN)(void *,
    const PAPACC_NETWORK_ENDPOINT *,PAPACC_U32);
typedef struct PAPACC_EGRESS_POLICY {
    PAPACC_BOOL master_enabled;
    PAPACC_U32 explicitly_allowed_sensitive_classes;
    PAPACC_EGRESS_HOST_POLICY_FN host_policy;
    PAPACC_EGRESS_ENDPOINT_POLICY_FN endpoint_policy;
    void *context;
} PAPACC_EGRESS_POLICY;
#define PAPACC_EGRESS_POLICY_INITIALIZER {PAPACC_FALSE,0U,NULL,NULL,NULL}

PAPACC_RESULT papacc_egress_profile_validate(const PAPACC_EGRESS_PROFILE *);
PAPACC_U32 papacc_egress_endpoint_sensitive_classes(
    const PAPACC_NETWORK_ENDPOINT *);
PAPACC_BOOL papacc_egress_hostname_allowed(const PAPACC_EGRESS_POLICY *,
    const char *,PAPACC_SIZE,PAPACC_U16);
PAPACC_BOOL papacc_egress_endpoint_allowed(const PAPACC_EGRESS_POLICY *,
    const PAPACC_NETWORK_ENDPOINT *);

#endif
